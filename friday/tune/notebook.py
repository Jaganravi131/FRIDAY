"""Emit the Colab notebook for the free-T4 fine-tuning run (docs/architecture/18 §4.3).

A notebook is just JSON. Generating it from here — rather than keeping a static
copy in the repo — means the model table in models.py and the notebook can never
drift apart: bump a default there and the next `friday tune --notebook` emits it.

The run it encodes:
  install unsloth + stack  →  upload friday_dataset.jsonl  →  load base in 4-bit
  →  attach LoRA  →  train ~2 epochs on the personal dataset  →  merge
  →  llama.cpp convert to Q4_K_M GGUF  →  download  →  print next steps (bench gate).

Every cell is deliberately boring: no magic flags, no background processes, and
each phase prints what it is doing so a failed run says WHERE it failed.
"""
from __future__ import annotations

import json

from .models import default_choice


def _md(source: str) -> dict:
    return {"cell_type": "markdown", "metadata": {},
            "source": source.strip("\n").splitlines(keepends=True)}


def _code(source: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None,
            "outputs": [], "source": source.strip("\n").splitlines(keepends=True)}


def build_notebook(*, base_repo: str | None = None, epochs: int = 2,
                   dataset_name: str = "friday_dataset.jsonl",
                   out_name: str = "friday-personal") -> dict:
    base = base_repo or default_choice().repo
    cells: list[dict] = []

    cells.append(_md(f"""# FRIDAY personal fine-tune — QLoRA on a free Colab T4

Base model: **{base}** · dataset: `{dataset_name}` · output: `{out_name}.gguf` (Q4_K_M)

This notebook was generated by `friday tune --notebook` (docs/architecture/18).
Runtime → Change runtime type → **T4 GPU**, then Runtime → Run all.
Expected wall time: 20–60 minutes depending on dataset size and epochs."""))

    cells.append(_md("## 1 · Install (unsloth + training stack)"))
    cells.append(_code("""# unsloth gives the 2-5x memory/speed advantage that makes a free T4 viable.
!pip install -q "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git"
!pip install -q --no-deps "xformers<0.0.27" "trl<0.9.0" "peft>=0.11" "accelerate" "bitsandbytes"
!pip install -q datasets sentencepiece
print("stack installed")"""))

    cells.append(_md("## 2 · Upload the dataset"))
    cells.append(_code(f"""from google.colab import files
print("Upload {dataset_name} (built by `friday tune --export`):")
up = files.upload()
assert "{dataset_name}" in up, f"expected {dataset_name} in upload, got {{list(up)}}"
import json
rows = [json.loads(l) for l in open("{dataset_name}", encoding="utf-8")]
print(f"{{len(rows)}} training examples")
assert len(rows) >= 50, "too few rows to teach anything — collect more memory first"
print(json.dumps(rows[0], indent=2)[:600])"""))

    cells.append(_md(f"## 3 · Load the base model (4-bit)"))
    cells.append(_code(f"""import torch
from unsloth import FastLanguageModel

BASE = "{base}"
model, tok = FastLanguageModel.from_pretrained(
    model_name=BASE,
    max_seq_length=2048,
    load_in_4bit=True,            # QLoRA: 4-bit weights, LoRA on top
)
model = FastLanguageModel.get_peft_model(
    model, r=16, lora_alpha=16, lora_dropout=0,
    target_modules=["q_proj","k_proj","v_proj","o_proj","gate_proj","up_proj","down_proj"],
    use_gradient_checkpointing="unsloth",
)
print("base loaded:", BASE)"""))

    cells.append(_md("## 4 · Train"))
    cells.append(_code(f"""from datasets import Dataset
from trl import SFTTrainer, SFTConfig

raw = [json.loads(l) for l in open("{dataset_name}", encoding="utf-8")]
def to_text(r):
    msgs = r["messages"]
    return "".join(
        ("<|im_start|>system\\n" if m["role"]=="system" else
         "<|im_start|>user\\n" if m["role"]=="user" else
         "<|im_start|>assistant\\n") + m["content"] + "<|im_end|>\\n"
        for m in msgs)
ds = Dataset.from_dict({{"text": [to_text(r) for r in raw]}})

trainer = SFTTrainer(
    model=model, tokenizer=tok, train_dataset=ds, dataset_text_field="text",
    max_seq_length=2048, packing=True,
    args=SFTConfig(
        per_device_train_batch_size=2, gradient_accumulation_steps=4,
        num_train_epochs={epochs}, learning_rate=2e-4, warmup_steps=10,
        logging_steps=10, output_dir="runs", report_to=[],
        fp16=not torch.cuda.is_bf16_supported(), bf16=torch.cuda.is_bf16_supported(),
        optim="adamw_8bit", seed=42,
    ),
)
stats = trainer.train()
print("train done:", stats.training_loss)"""))

    cells.append(_md("## 5 · Smoke-test BEFORE merge (a bad run must not ship)"))
    cells.append(_code("""FastLanguageModel.for_inference(model)
probe = [{"role":"system","content":"You are FRIDAY."},
         {"role":"user","content":"What do you know about me?"}]
text = "<|im_start|>system\\nYou are FRIDAY.<|im_end|>\\n<|im_start|>user\\nWhat do you know about me?<|im_end|>\\n<|im_start|>assistant\\n"
out = model.generate(**tok(text, return_tensors="pt").to("cuda"),
                     max_new_tokens=200, temperature=0.3)
print(tok.decode(out[0], skip_special_tokens=True)[-800:])"""))

    cells.append(_md(f"## 6 · Merge + convert to GGUF (Q4_K_M) + download"))
    cells.append(_code(f"""# save_pretrained_gguf runs the llama.cpp conversion inside unsloth's bundled
# toolchain; Q4_K_M is the per-layer mix that gives the best size/quality at ~4-5 GB.
model.save_pretrained_gguf("{out_name}", tok, quantization_method="q4_k_m")
import glob
hits = glob.glob("{out_name}/**/*.gguf", recursive=True) or glob.glob("**/*.gguf", recursive=True)
assert hits, "no GGUF produced — check the step above for converter errors"
print("GGUF ready:", hits[0])
from google.colab import files
files.download(hits[0])"""))

    cells.append(_md(f"""## 7 · Back on the laptop — the gate, not vibes

1. Put the downloaded `.gguf` somewhere stable, e.g. `~/models/{out_name}-q4_k_m.gguf`.
2. Point llama-server at it in FRIDAY's config: `friday config model.path ~/models/{out_name}-q4_k_m.gguf`.
3. **Law 10: run the gate before it answers real questions.**

```
friday bench --gate        # must be >= the recorded baseline
python scripts/needle_test.py
```

If the bench regresses, revert `model.path` to the last good GGUF. A fine-tuned
model that retrieves your life worse than the base model is not an upgrade,
whatever the loss curve said."""))

    return {"cells": cells,
            "metadata": {"accelerator": "GPU",
                         "colab": {"provenance": [], "gpuType": "T4"},
                         "kernelspec": {"display_name": "Python 3", "name": "python3"},
                         "language_info": {"name": "python"}},
            "nbformat": 4, "nbformat_minor": 5}


def write_notebook(path, **kw) -> int:
    nb = build_notebook(**kw)
    text = json.dumps(nb, indent=1, ensure_ascii=False)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text + "\n", encoding="utf-8")
    return len(text.encode("utf-8"))
