"""Adapters between the HUD's REST vocabulary and FRIDAY's real stores.

The HUD was written against a simpler memory model (sessions with titles, facts
with autogenerated ids, a `stats` block). The cognition core has a stricter one:
bi-temporal facts, `turns` rows, `sessions.scope` constrained by a CHECK, and no
titles at all. Rather than bend either side, this module translates.

Two rules held throughout:

  * **Reads never invent state.** A session title is derived from `sessions.topic`
    or the first user turn; if neither exists the title is "Untitled". Nothing is
    written back just because the UI asked to list.
  * **Writes go through the core's own chokepoints.** Adding a memory calls
    `assert_fact` (so redaction, reconciliation, Markdown truth, FTS and
    supervision all happen exactly as they do for the agent). Forgetting calls
    `retract_fact`, which retracts rather than deletes: Law 2b says memory is a
    ledger, and a fact that was once believed is part of the record.

The HUD itself is unchanged; that is the point of an adapter.
"""

from __future__ import annotations

import json
import os
import platform
import shutil
import sqlite3
import time
from pathlib import Path
from typing import Any

from .. import paths
from ..memory.facts import Fact, assert_fact, current_facts, retract_fact
from ..util import new_id, now_iso

# ── connections ────────────────────────────────────────────────────────────────

def connect(db_path: Path | str | None = None) -> sqlite3.Connection:
    from ..store import db

    return db.connect(db_path or paths.DB_PATH)


def _row_to_session(row: sqlite3.Row) -> dict[str, Any]:
    first = row["first_user"] or ""
    title = row["topic"] or (first[:60] + ("…" if len(first) > 60 else "")) or "Untitled"
    return {
        "id": row["id"],
        "title": title,
        "created_at": row["started_at"],
        "updated_at": row["last_ts"] or row["started_at"],
        "message_count": int(row["message_count"] or 0),
        "scope": row["scope"],
    }


_SESSION_QUERY = """
    SELECT s.id, s.started_at, s.scope, s.topic,
           (SELECT COUNT(*) FROM turns t WHERE t.session_id = s.id) AS message_count,
           (SELECT MAX(t.ts) FROM turns t WHERE t.session_id = s.id) AS last_ts,
           (SELECT t.content FROM turns t
             WHERE t.session_id = s.id AND t.role = 'user'
             ORDER BY t.idx ASC LIMIT 1) AS first_user
      FROM sessions s
"""


def list_sessions(conn: sqlite3.Connection, limit: int = 100) -> list[dict[str, Any]]:
    rows = conn.execute(
        _SESSION_QUERY + " ORDER BY COALESCE(last_ts, s.started_at) DESC LIMIT ?", (limit,)
    ).fetchall()
    return [_row_to_session(r) for r in rows]


def get_session(conn: sqlite3.Connection, session_id: str) -> dict[str, Any] | None:
    row = conn.execute(_SESSION_QUERY + " WHERE s.id = ?", (session_id,)).fetchone()
    if row is None:
        return None
    session = _row_to_session(row)
    turns = conn.execute(
        "SELECT id, idx, ts, role, content FROM turns WHERE session_id = ? "
        "ORDER BY idx, role DESC",   # user before assistant within one exchange
        (session_id,),
    ).fetchall()
    session["messages"] = [
        {
            "id": t["id"],
            "role": t["role"],
            "content": t["content"] or "",
            "created_at": t["ts"],
            "meta": {},
        }
        for t in turns
        if t["role"] in ("user", "assistant", "tool")
    ]
    return session


def create_session(conn: sqlite3.Connection, title: str = "New session",
                   scope: str = "remote") -> dict[str, Any]:
    """Create a session. `remote` is a user-present scope, not an unattended one.

    A database built before the gateway existed carries a CHECK without `remote`
    and will reject it. Falling back to `interactive` keeps the UI working; the
    caller prints the same warning the stdlib gateway prints, and `friday rebuild`
    (safe: artifacts are derived) is the fix.
    """
    session_id = new_id("s")
    for candidate in (scope, "interactive"):
        try:
            conn.execute(
                "INSERT INTO sessions(id, started_at, scope, surfaces, topic, turn_count)"
                " VALUES (?,?,?,?,?,0)",
                (session_id, now_iso(), candidate, json.dumps(["web"]), title),
            )
            conn.commit()
            break
        except sqlite3.IntegrityError:
            if candidate == "interactive":
                raise
    return get_session(conn, session_id) or {"id": session_id}


def rename_session(conn: sqlite3.Connection, session_id: str, title: str) -> bool:
    cur = conn.execute("UPDATE sessions SET topic=? WHERE id=?", (title, session_id))
    conn.commit()
    return cur.rowcount > 0


def delete_session(conn: sqlite3.Connection, session_id: str) -> bool:
    conn.execute("DELETE FROM turns WHERE session_id=?", (session_id,))
    cur = conn.execute("DELETE FROM sessions WHERE id=?", (session_id,))
    conn.commit()
    return cur.rowcount > 0


def search_history(conn: sqlite3.Connection, query: str, limit: int = 25) -> list[dict]:
    like = f"%{query}%"
    rows = conn.execute(
        "SELECT id, session_id, ts, role, content FROM turns"
        " WHERE content LIKE ? ORDER BY ts DESC LIMIT ?",
        (like, limit),
    ).fetchall()
    return [dict(r) for r in rows]


# ── memory ─────────────────────────────────────────────────────────────────────

def _fact_text(row: sqlite3.Row) -> str:
    predicate = str(row["predicate"]).replace("_", " ")
    return f"{predicate}: {row['object']}"


def list_facts(conn: sqlite3.Connection, limit: int = 200) -> list[dict[str, Any]]:
    items = []
    for row in current_facts(conn, limit=limit):
        items.append({
            "id": row["id"],
            "text": _fact_text(row),
            "subject": row["subject"],
            "predicate": row["predicate"],
            "object": row["object"],
            "domain": row["origin_file"],
            "confidence": row["confidence"],
            "asserted_at": row["asserted_at"],
            "valid_from": row["valid_from"],
        })
    return items


def add_fact(conn: sqlite3.Connection, text: str) -> dict[str, Any]:
    """Store a free-text memory as a `note` fact.

    A single textarea cannot supply the (subject, predicate, object) triple the
    fact compiler wants, so the predicate is explicitly `note`: it says exactly
    what happened — the user asserted something durable — and it does not pretend
    to be a structured claim. The agent can later reconcile it into a precise
    predicate through `memory_write`.
    """
    fact = Fact(subject="user", predicate="note", object=text.strip(),
                source_kind="stated")
    report = assert_fact(conn, fact)
    report["id"] = fact.id
    report["text"] = _fact_text({
        "predicate": fact.predicate, "object": fact.object,
    })
    return report


def forget_fact(conn: sqlite3.Connection, fact_id: str) -> bool:
    return retract_fact(conn, fact_id)


def stats(conn: sqlite3.Connection) -> dict[str, int]:
    def count(sql: str, args: tuple = ()) -> int:
        try:
            return int(conn.execute(sql, args).fetchone()[0])
        except sqlite3.Error:
            return 0

    return {
        "sessions": count("SELECT COUNT(*) FROM sessions"),
        "memories": count("SELECT COUNT(*) FROM facts WHERE retracted_at IS NULL"),
        "facts": count("SELECT COUNT(*) FROM facts"),
        "retracted": count("SELECT COUNT(*) FROM facts WHERE retracted_at IS NOT NULL"),
        "skills": count("SELECT COUNT(*) FROM skills"),
        "turns": count("SELECT COUNT(*) FROM turns"),
    }


# ── host telemetry ─────────────────────────────────────────────────────────────

def _memory_used_pct() -> float:
    try:
        info: dict[str, int] = {}
        with open("/proc/meminfo", encoding="utf-8") as fh:
            for line in fh:
                key, _, rest = line.partition(":")
                info[key] = int(rest.strip().split()[0])
        total = info.get("MemTotal", 0)
        available = info.get("MemAvailable", info.get("MemFree", 0))
        return round((total - available) / total * 100, 1) if total else 0.0
    except (OSError, ValueError):
        return 0.0


def telemetry() -> dict[str, Any]:
    load_1m = 0.0
    try:
        load_1m = os.getloadavg()[0]
    except (OSError, AttributeError):
        pass
    disk = shutil.disk_usage(str(paths.ROOT))
    return {
        "hostname": platform.node() or "localhost",
        "platform": platform.platform(),
        "cpu_count": os.cpu_count() or 1,
        "load_1m": round(load_1m, 2),
        "memory": {"used_pct": _memory_used_pct()},
        "disk": {"used_pct": round(disk.used / disk.total * 100, 1)},
        "time": time.time(),
    }


def artifact_sizes() -> dict[str, int]:
    out: dict[str, int] = {}
    if paths.ARTIFACTS.is_dir():
        for p in paths.ARTIFACTS.iterdir():
            if p.is_file():
                out[p.name] = p.stat().st_size
    return out
